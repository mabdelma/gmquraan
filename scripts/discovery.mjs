#!/usr/bin/env node
/**
 * Gate 0 baseline generator.
 *
 * The mechanical parts of discovery — what models exist, what endpoints exist,
 * what the workspace graph is, what tests there are — are read out of the
 * repository rather than typed into a document. A baseline that is maintained
 * by hand is a baseline that is wrong by the second week, and the whole point
 * of Gate 0 is that later waves can trust it.
 *
 * The analytical documents (architecture narrative, fit-gap classification,
 * implementation waves) are written by hand because they are judgement, and
 * judgement that claims to be generated is worse than judgement that admits it.
 *
 *   node scripts/discovery.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from "fs";
import { join, relative } from "path";

const ROOT = process.cwd();
const OUT = join(ROOT, "docs", "generated");
mkdirSync(OUT, { recursive: true });

const SKIP = new Set(["node_modules", ".git", ".next", "dist", "build", ".turbo", "generated"]);

function walk(dir, hit, acc = []) {
  if (!existsSync(dir)) return acc;
  for (const name of readdirSync(dir)) {
    if (SKIP.has(name)) continue;
    const p = join(dir, name);
    let s;
    try {
      s = statSync(p);
    } catch {
      continue;
    }
    if (s.isDirectory()) walk(p, hit, acc);
    else if (hit(name, p)) acc.push(p);
  }
  return acc;
}

const rel = (p) => relative(ROOT, p).split("\\").join("/");
const stamp = new Date().toISOString().slice(0, 10);

const header = (title, note) =>
  `# ${title}\n\n> Generated by \`scripts/discovery.mjs\` on ${stamp}. Do not edit by hand —\n> re-run the script. ${note}\n\n`;

// ── Data model ─────────────────────────────────────────────────────────────
function dataModel() {
  const schemas = walk(join(ROOT, "packages", "db", "prisma"), (n) => n.endsWith(".prisma"));
  let out = header(
    "Database schema baseline",
    "Compare against `APP_Core_Developer_Exact_V2/data/sql/` — that DDL is a reference design, not permission to replace this schema."
  );

  for (const file of schemas) {
    const src = readFileSync(file, "utf8");
    const models = [...src.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)];
    const enums = [...src.matchAll(/^enum\s+(\w+)\s*\{/gm)].map((m) => m[1]);

    out += `## \`${rel(file)}\`\n\n`;
    out += `${models.length} models, ${enums.length} enums.\n\n`;
    out += `| Model | Fields | Money fields | Relations | Indexes |\n|---|---|---|---|---|\n`;

    for (const [, name, body] of models) {
      const lines = body.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("//") && !l.startsWith("///"));
      const fields = lines.filter((l) => /^\w+\s+\S/.test(l) && !l.startsWith("@@"));
      // Float on money is a defect. Int is not: integer minor units (cents) is a
      // correct representation and is what the payment models here already use.
      // Flagging Int too made the first run report three sound fields as bugs.
      const money = fields.filter((l) => /(amount|price|cost|total|salary|net|gross|value|fee|rate)/i.test(l.split(/\s+/)[0]));
      const moneyBad = money.filter((l) => /\bFloat\b/.test(l));
      const relations = fields.filter((l) => /@relation/.test(l));
      const idx = lines.filter((l) => l.startsWith("@@index") || l.startsWith("@@unique"));
      const moneyCell = money.length
        ? `${money.length}${moneyBad.length ? ` ⚠️ ${moneyBad.length} non-decimal` : ""}`
        : "—";
      out += `| ${name} | ${fields.length} | ${moneyCell} | ${relations.length} | ${idx.length} |\n`;
    }
    out += "\n";
  }

  // Money-type audit, called out separately because it is a correctness gate.
  out += `## Monetary type audit\n\n`;
  out += `The specification forbids floating point for accounting amounts. Two representations\n`;
  out += `satisfy that: decimal/numeric, and integer minor units. This repository uses integer\n`;
  out += `minor units (\`Int // cents\`) in its payment models, which is sound, so only \`Float\`\n`;
  out += `is reported as a defect below.\n\n`;
  let flagged = 0;
  let minorUnits = 0;
  for (const file of schemas) {
    const src = readFileSync(file, "utf8");
    for (const [, name, body] of src.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)) {
      for (const line of body.split("\n")) {
        const t = line.trim();
        const fieldName = t.split(/\s+/)[0] || "";
        if (!/(amount|price|cost|total|salary|net|gross|value|fee)/i.test(fieldName)) continue;
        if (/\bFloat\b/.test(t)) {
          out += `- ⚠️ **\`${name}.${fieldName}\`** uses \`Float\` in ${rel(file)}\n`;
          flagged++;
        } else if (/\bInt\b/.test(t)) {
          minorUnits++;
        }
      }
    }
  }
  if (!flagged) out += `No monetary field uses Float.\n`;
  out += `\n**Float defects: ${flagged}. Integer minor-unit fields: ${minorUnits}.**\n\n`;
  out += `Note for FIN-01: there is no \`Decimal\` anywhere in the schema today. A general\n`;
  out += `ledger with multi-currency and tax needs one money representation across the whole\n`;
  out += `domain, so which of the two to standardise on is a Wave 2 decision item rather than\n`;
  out += `something to settle per table.\n\n`;

  out += `## Migration model\n\n`;
  const migDir = join(ROOT, "packages", "db", "prisma", "migrations");
  out += existsSync(migDir)
    ? `\`prisma migrate\` — ${readdirSync(migDir).length} migrations.\n`
    : `No \`migrations/\` directory. Deployment reconciles with \`prisma db push\`, which means the\nschema file is the only description of the database and there is no ordered,\nreviewable history of changes. Recorded here as a baseline fact; changing it is\na Wave 1 decision item.\n`;

  writeFileSync(join(OUT, "DB_SCHEMA_BASELINE.md"), out);
  return { models: schemas.length };
}

// ── API ────────────────────────────────────────────────────────────────────
function api() {
  const apps = ["web", "workforce", "agent"];
  let out = header(
    "API baseline",
    "Compare against `APP_Core_Developer_Exact_V2/api/API_ENDPOINT_CATALOG.md` and `api/openapi/app-core.openapi.json`."
  );

  let total = 0;
  for (const app of apps) {
    const base = join(ROOT, "apps", app, "src", "app");
    const routes = walk(base, (n) => n === "route.ts");
    if (!routes.length) continue;

    out += `## apps/${app} — ${routes.length} endpoints\n\n`;
    out += `| Path | Methods | Auth guard | Audit write |\n|---|---|---|---|\n`;

    for (const r of routes.sort()) {
      const src = readFileSync(r, "utf8");
      const methods = [...src.matchAll(/export\s+async\s+function\s+(GET|POST|PUT|PATCH|DELETE|HEAD)/g)].map((m) => m[1]);
      const path = rel(r).replace(`apps/${app}/src/app`, "").replace("/route.ts", "") || "/";
      // Named guards used in this codebase, plus the generic session reads.
      const guard =
        /memberOr401|requireMember|getCentralAdmin|getSessionUser|getMember|getPendingMember|isAdmin|isPartner/.test(src)
          ? "yes"
          : /limited\(/.test(src)
            ? "rate-limit only"
            : "**none found**";
      const audit = /auditLog\.create|documentEvent\.create|folderEvent\.create|taskEvent\.create|domainEvent\.create|agentRun\.create/.test(src)
        ? "yes"
        : "—";
      out += `| \`${path}\` | ${methods.join(", ") || "—"} | ${guard} | ${audit} |\n`;
      total++;
    }
    out += "\n";
  }

  out += `**Total endpoints: ${total}**\n\n`;
  out += `\`Auth guard\` reports whether a known guard symbol appears in the file. It is a\ntextual signal, not a proof of correct authorization — endpoints marked \`none found\`\nare the ones to review first, and a \`yes\` still has to be checked for *which*\nscope it enforces.\n`;

  writeFileSync(join(OUT, "API_BASELINE.md"), out);
  return { total };
}

// ── Dependencies ───────────────────────────────────────────────────────────
function deps() {
  const pkgs = walk(ROOT, (n) => n === "package.json").filter((p) => !rel(p).includes("node_modules"));
  let out = header("Dependency map", "Workspace graph and external dependency surface.");

  const rootPkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8"));
  out += `## Workspaces\n\n\`${JSON.stringify(rootPkg.workspaces)}\`\n\n`;

  out += `## Packages\n\n| Package | Path | Internal deps | External deps |\n|---|---|---|---|\n`;
  const internal = new Map();
  for (const p of pkgs.sort()) {
    if (rel(p) === "package.json") continue;
    const j = JSON.parse(readFileSync(p, "utf8"));
    const d = { ...(j.dependencies || {}), ...(j.devDependencies || {}) };
    const int = Object.keys(d).filter((k) => k.startsWith("@app/"));
    const ext = Object.keys(d).filter((k) => !k.startsWith("@app/"));
    internal.set(j.name, int);
    out += `| \`${j.name || "(unnamed)"}\` | ${rel(p).replace("/package.json", "")} | ${int.join(", ") || "—"} | ${ext.length} |\n`;
  }

  out += `\n## Internal graph\n\n\`\`\`mermaid\ngraph TD\n`;
  for (const [name, ints] of internal) {
    if (!name) continue;
    const from = name.replace("@app/", "");
    if (!ints.length) out += `  ${from}\n`;
    for (const i of ints) out += `  ${from} --> ${i.replace("@app/", "")}\n`;
  }
  out += `\`\`\`\n\n`;

  // Worth listing, but not all of them are dead weight: mobile/ is a Capacitor
  // native shell and legitimately sits outside a JavaScript workspace. An
  // earlier revision of this report called it an orphan alongside two genuinely
  // stale duplicates, which was wrong. List them; judging them stays human.
  out += `## Trees outside the workspace globs\n\n`;
  out += `Listed, not condemned — a native shell legitimately sits outside a JS workspace.\n\n`;
  const globs = (rootPkg.workspaces || []).map((g) => g.replace("/*", ""));
  const orphans = readdirSync(ROOT).filter((n) => {
    if (SKIP.has(n) || globs.includes(n)) return false;
    try {
      return statSync(join(ROOT, n)).isDirectory() && existsSync(join(ROOT, n, "package.json"));
    } catch {
      return false;
    }
  });
  out += orphans.length
    ? orphans.map((o) => `- \`${o}/\` — has a package.json but is not in a workspace glob\n`).join("")
    : "None.\n";

  writeFileSync(join(OUT, "DEPENDENCY_MAP.md"), out);
  return { orphans };
}

// ── Tests ──────────────────────────────────────────────────────────────────
function tests() {
  const files = walk(ROOT, (n) => /\.(test|spec)\.[tj]sx?$/.test(n));
  let out = header("Test baseline", "Compare against `APP_Core_Developer_Exact_V2/tests/test_catalog.csv`.");

  const byArea = new Map();
  let cases = 0;
  for (const f of files) {
    const src = readFileSync(f, "utf8");
    const n = (src.match(/^\s*(it|test)\(/gm) || []).length;
    cases += n;
    const area = rel(f).split("/").slice(0, 2).join("/");
    byArea.set(area, (byArea.get(area) || 0) + n);
  }

  out += `## Where tests exist\n\n| Area | Test cases |\n|---|---|\n`;
  for (const [a, n] of [...byArea].sort((x, y) => y[1] - x[1])) out += `| \`${a}\` | ${n} |\n`;
  out += `\n**${files.length} files, ${cases} cases.**\n\n`;

  out += `## Test kinds present\n\n`;
  const kinds = {
    "unit / domain": files.filter((f) => rel(f).includes("packages/")).length,
    "app / route": files.filter((f) => rel(f).includes("apps/")).length,
    "service": files.filter((f) => rel(f).includes("services/")).length,
  };
  for (const [k, n] of Object.entries(kinds)) out += `- ${k}: ${n} file(s)\n`;

  out += `\n## Kinds the specification requires that are absent\n\n`;
  const required = [
    ["database/migration tests", /migration|schema/i],
    ["API contract tests", /openapi|contract/i],
    ["cross-company security tests", /cross.?company|tenant.?isolation|company.?scope/i],
    ["event idempotency tests", /idempoten/i],
    ["e2e / UI tests", /playwright|e2e|cypress/i],
    ["AI authorization / eval tests", /rag|prompt.?injection|ai.?eval/i],
  ];
  const all = files.map((f) => readFileSync(f, "utf8") + rel(f)).join("\n");
  for (const [label, re] of required) {
    out += `- ${re.test(all) ? "present" : "**absent**"} — ${label}\n`;
  }

  writeFileSync(join(OUT, "TEST_BASELINE.md"), out);
  return { files: files.length, cases };
}

const d = dataModel();
const a = api();
const p = deps();
const t = tests();

console.log(`DB_SCHEMA_BASELINE.md   ${d.models} prisma schema file(s)`);
console.log(`API_BASELINE.md         ${a.total} endpoints`);
console.log(`DEPENDENCY_MAP.md       ${p.orphans.length} tree(s) outside the workspace globs`);
console.log(`TEST_BASELINE.md        ${t.files} files, ${t.cases} cases`);
